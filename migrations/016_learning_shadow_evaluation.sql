CREATE TABLE IF NOT EXISTS learning_shadow_evaluations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  actor_id BIGINT UNSIGNED NOT NULL,
  model_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  configuration_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  scenario_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  rule_versions_json JSON NOT NULL,
  retrieval_context_json JSON NOT NULL,
  sampling_json JSON NOT NULL,
  requested_samples TINYINT UNSIGNED NOT NULL,
  completed_samples TINYINT UNSIGNED NOT NULL DEFAULT 0,
  provider_calls SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  estimated_max_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  results_json JSON NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'running',
  failure_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  INDEX learning_shadow_created (created_at, id),
  INDEX learning_shadow_actor (actor_id, created_at),
  INDEX learning_shadow_status_created (status, created_at),
  FOREIGN KEY (actor_id) REFERENCES admins(id) ON DELETE RESTRICT,
  CHECK (requested_samples BETWEEN 1 AND 3),
  CHECK (completed_samples <= requested_samples),
  CHECK (provider_calls <= 12),
  CHECK (estimated_max_tokens <= 30000),
  CHECK (JSON_LENGTH(rule_versions_json) <= 5),
  CHECK (status IN ('running','completed','incomplete','failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS learning_shadow_reviews (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  evaluation_id BIGINT UNSIGNED NOT NULL,
  sample_index TINYINT UNSIGNED NOT NULL,
  variant VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reviewer_id BIGINT UNSIGNED NOT NULL,
  feedback_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  ratings_json JSON NOT NULL,
  explanation VARCHAR(1000) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY shadow_review_reviewer (evaluation_id, sample_index, variant, reviewer_id),
  INDEX shadow_review_created (created_at),
  FOREIGN KEY (evaluation_id) REFERENCES learning_shadow_evaluations(id) ON DELETE RESTRICT,
  FOREIGN KEY (reviewer_id) REFERENCES admins(id) ON DELETE RESTRICT,
  CHECK (sample_index BETWEEN 1 AND 3),
  CHECK (variant IN ('baseline','learning')),
  CHECK (feedback_type IN ('positive','negative'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
